"""Write nes_harbor/nes/ports.inc: NES Harbor's list of preset ports.

Each port is a name for the picker (up to NAME_LEN characters, drawn with
the scope's font: capitals, digits, space, + - . / :) and the middle of the
scope, in millionths of a degree, as HARBOR's PLACE request wants it.

    tools/gen_ports.py nes_harbor/nes/ports.inc
"""
