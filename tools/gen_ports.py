def tiles(name):
    name = name.upper().ljust(NAME_LEN)
    if len(name) > NAME_LEN:
        raise ValueError(f"{name!r} is longer than {NAME_LEN}")
    out = []
    for ch in name:
        if ch not in FONT:
            raise ValueError(f"{ch!r} in {name!r} is not in the scope's font")
        out.append(FONT.index(ch))
    return out


def main(path):
    lines = [
        "; Generated by tools/gen_ports.py. Do not hand-edit.",
        f"PORT_COUNT = {len(PORTS)}",
        f"PORT_NAME_LEN = {NAME_LEN}",
        "",
        "; Each port's name as font tiles (add FONT_BASE), NAME_LEN of them.",
        "port_names:",
    ]
    for name, _, _, _ in PORTS:
        lines.append("    .byte " + ",".join(f"${t:02X}" for t in tiles(name)) + f"   ; {name}")
    lines += ["", "; Each port's middle: latitude then longitude, signed 32-bit little-endian,",
              "; millionths of a degree (HARBOR PLACE, kind COORDS).", "port_places:"]
    for name, lat, lon, _ in PORTS:
        raw = struct.pack("<ii", round(lat * 1_000_000), round(lon * 1_000_000))
        lines.append("    .byte " + ",".join(f"${b:02X}" for b in raw) + f"   ; {name}")
    lines += ["", "; Each port's tag for the scope's corner: four ASCII capitals or spaces.", "port_tags:"]
    for name, _, _, tag in PORTS:
        if len(tag) > 4 or not all(c in FONT for c in tag):
            raise ValueError(f"tag {tag!r} of {name!r}")
        lines.append('    .byte "' + tag.rjust(4) + f'"   ; {name}')
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(PORTS)} ports -> {path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "nes_harbor/nes/ports.inc")
