#!/usr/bin/env python3
"""Write nes_harbor/nes/music_data.inc: NES Harbor's tunes, for music.inc.

A tune is two voices, the first square wave's melody and the triangle's
bass, each a list of notes: a name and octave ("A4", "C#5", "R" for a
rest) and a length in sixteenths. The driver plays a sixteenth as
SIXTEENTH frames. Each voice of a looping tune goes back to its start when
it ends, so a tune's voices must be the same length.

    tools/gen_music.py nes_harbor/nes/music_data.inc

Drunken Sailor is a traditional sea shanty, in the public domain. The
fanfare is NES Harbor's own.
"""
import sys

CPU_HZ = 1789773
NAMES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7,
         "G#": 8, "A": 9, "A#": 10, "B": 11}
LOWEST = 2 * 12                  # C2 is note 1 in the tables


def midi(name):
    return (int(name[-1]) + 1) * 12 + NAMES[name[:-1]]


def notes(text):
    out = []
    for word in text.split():
        name, length = word.split(":")
        out.append((name, int(length)))
    return out


# Drunken Sailor, in D dorian: a verse and a chorus of four lines, a line
# 32 sixteenths.
VERSE_1 = "A4:4 A4:2 A4:2 A4:4 A4:2 A4:2 A4:4 D4:4 F4:4 A4:4"
VERSE_2 = "G4:4 G4:2 G4:2 G4:4 G4:2 G4:2 G4:4 C4:4 E4:4 G4:4"
VERSE_4 = "C5:4 A4:4 G4:4 E4:4 D4:8 R:8"
SAILOR_MELODY = " ".join([
    VERSE_1, VERSE_2, VERSE_1.replace("D4:4 F4:4 A4:4", "B4:4 C5:4 D5:4"), VERSE_4,
    "A4:8 A4:8 A4:4 D4:4 F4:4 A4:4",          # way hay and up she rises
    "G4:8 G4:8 G4:4 C4:4 E4:4 G4:4",
    "A4:8 A4:8 A4:4 B4:4 C5:4 D5:4",
    "C5:4 A4:4 G4:4 E4:4 D4:8 R:8",            # early in the morning
])
D_BAR = "D3:4 A2:4 D3:4 A2:4 D3:4 A2:4 D3:4 A2:4"
C_BAR = "C3:4 G2:4 C3:4 G2:4 C3:4 G2:4 C3:4 G2:4"
END_BAR = "C3:4 G2:4 C3:4 G2:4 D3:4 A2:4 D3:4 R:4"
SAILOR_BASS = " ".join([D_BAR, C_BAR, D_BAR, END_BAR] * 2)  # a line: 32 sixteenths

FANFARE_MELODY = "D4:2 R:1 D4:1 F#4:1 A4:2 D5:6 R:3"   # the splash's two seconds
FANFARE_BASS = "D3:8 D3:8"

TUNES = [
    ("tune_sailor", SAILOR_MELODY, SAILOR_BASS, True),
    ("tune_fanfare", FANFARE_MELODY, FANFARE_BASS, False),
]


def period(m, divisor):
    f = 440.0 * 2 ** ((m - 69) / 12)
    return max(0, min(0x7FF, round(CPU_HZ / (divisor * f)) - 1))


def main(path):
    lines = ["; Generated by tools/gen_music.py. Do not hand-edit.", "",
             "; A note's square-wave period, low and high, by note: C2 is note 1.",
             "; The triangle's is the note an octave up's (it halves its rate)."]
    count = 60
    lows = [period(LOWEST + i, 16) for i in range(count)]
    lines.append("note_period_lo:")
    lines.append("    .byte 0," + ",".join(f"${p & 0xFF:02X}" for p in lows))
    lines.append("note_period_hi:")
    lines.append("    .byte 0," + ",".join(f"${p >> 8:02X}" for p in lows))
    for name, melody, bass, loop in TUNES:
        for voice, text in (("melody", melody), ("bass", bass)):
            seq = notes(text)
            total = sum(n for _, n in seq)
            if voice == "melody":
                length = total
            elif total != length:
                sys.exit(f"{name}: the bass is {total} sixteenths, the melody {length}")
            data = []
            for note, n in seq:
                code = 0 if note == "R" else midi(note) - LOWEST + 1
                if not 0 <= code <= count:
                    sys.exit(f"{name}: {note} is out of range")
                while n > 0:
                    data += [code, min(n, 64)]
                    n -= 64
            data.append(0xFF if loop else 0xFE)
            lines.append(f"{name}_{voice}:   ; {total} sixteenths")
            for i in range(0, len(data), 16):
                lines.append("    .byte " + ",".join(f"${b:02X}" for b in data[i:i + 16]))
    open(path, "w").write("\n".join(lines) + "\n")
    print(f"{len(TUNES)} tunes -> {path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "nes_harbor/nes/music_data.inc")
